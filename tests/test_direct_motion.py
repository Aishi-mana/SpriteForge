"""CPU direct animation motion reference regressions."""
from _common import *
from engine import direct_motion as M
a=Image.new("RGBA",(16,16))
a.paste((255,0,0,255),(2,3,6,9))
b=Image.new("RGBA",(16,16))
b.paste((255,0,0,255),(4,4,8,10))
doc=dict(version=1,name="motion",width=16,height=16,pivot=[8,15],fps=12,frames=[data_url(a),data_url(b)])
body=dict(document=doc,first=0,last=1)
r=M.inspect(body)
ok(r["frames"][0]["bounds"]==[2,3,6,9],"exclusive alpha bounds")
ok(r["frames"][1]["delta"]==[2.0,1.0],"centroid displacement")
ok(r["frames"][1]["ground_y"]==9,"ground edge")
ok(r["frames"][1]["time_ms"]==83.333,"original frame timing")
ok(M.sample_indices(0,1,12,9,24)==[0,0,1,1,1,1,1,1,1],"sample without temporal stretching, hold final")
frames,fps=M.render({**body,"kind":"silhouette","width":256,"height":256,"frames":9,"fps":12})
ok(len(frames)==9 and fps==12 and frames[0].size==(256,256),"guide dimensions and count")
ok(frames[0].tobytes()!=frames[1].tobytes() and frames[1].tobytes()==frames[-1].tobytes(),"guide preserves motion and tail hold")
ok(frames[0].getpixel((0,0))==(0,0,0),"black background")
try:M.inspect({**body,"last":2});ok(False,"reject invalid range")
except ValueError:ok(True,"reject invalid range")
try:M.render({**body,"frames":10});ok(False,"reject invalid Wan count")
except ValueError:ok(True,"reject invalid Wan count")
done("test_direct_motion")
