const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const html=fs.readFileSync(path.join(__dirname,'../../ui/index.html'),'utf8');
const code=html.split('/*IE61-WORKSPACE-START*/')[1].split('/*IE61-WORKSPACE-END*/')[0];
const api=new Function(code+'return {stage:ie61Stage,cache:IE61_WORK}')();
const {stage,cache}=api;
const a=stage(cache,'master','original','project-a',false);
a.result.sprite='edited';
assert.equal(a.source,'original');assert.equal(a.result.info.pipeline,'hd');
assert.equal(stage(cache,'master','original','project-a',false),a);
assert.equal(stage(cache,'master','original','project-a',false).result.sprite,'edited');
console.log('ok revisions staged independently of approved source');
const b=stage(cache,'sprite','original','project-a',true);
assert.notEqual(a,b);assert.equal(b.result.info.pipeline,'pixel');
const c=stage(cache,'master','changed','project-a',false);assert.notEqual(c,a);assert.equal(c.result.sprite,'changed');
const d=stage(cache,'master','changed','project-b',false);assert.notEqual(c,d);
console.log('ok source and project isolation');
const l1={},l2={};
assert.notEqual(stage(cache,'layer','same',l1,true),stage(cache,'layer','same',l2,true));
cache.clear();assert.notEqual(stage(cache,'master','changed','project-b',false),d);
console.log('ok layer identity and project reset');
assert(html.includes('IE61_WORK.clear();ca61Load'));
assert(html.includes('IE61_WORK.get(kind)===stage'));
assert(html.includes("ie61Workspace('master')"));
assert(html.includes("ie61Workspace('sprite')"));
assert(html.includes("ie61Workspace('body')"));
assert(html.includes("ie61Workspace('composite')"));
assert(html.includes("ie61Workspace('layer')"));
assert(html.includes('Existing modular layers remain unchanged.'));
console.log('ok workspace entry points and stale source guards');
