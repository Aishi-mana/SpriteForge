const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const html=fs.readFileSync(path.join(__dirname,'../../ui/index.html'),'utf8');
const code=html.split('/*IE61-HISTORY-START*/')[1].split('/*IE61-HISTORY-END*/')[0];
const api=new Function(code+'return {history:ie61History,commit:ie61Commit,restore:ie61Restore}')();
const r={sprite:'original',info:{size:[32,64]},rig:{}};
assert.equal(api.history(r).index,0);
assert(api.commit(r,{sprite:'mage',info:{size:[64,64]}},'Mage outfit'));
assert.equal(r.rig,undefined);assert.equal(r.sprite,'mage');
assert(api.commit(r,{sprite:'wings',info:{size:[96,96]}},'Add wings'));
assert(api.restore(r,1));assert.equal(r.sprite,'mage');assert.deepEqual(r.info.size,[64,64]);
assert(api.restore(r,2));assert.equal(r.sprite,'wings');
assert(api.restore(r,0));assert.equal(r.sprite,'original');assert.deepEqual(r.info.size,[32,64]);
console.log('ok exact revision restore and redo');
assert(api.commit(r,{sprite:'ranger',info:{}},'New branch'));
assert.deepEqual(api.history(r).entries.map(x=>x.sprite),['original','ranger']);
assert(!api.restore(r,99));assert(!api.commit(r,{sprite:'ranger',info:{}},'Duplicate'));
console.log('ok branching and invalid navigation');
for(let i=0;i<30;i++)api.commit(r,{sprite:'edit'+i,info:{}},'Edit '+i);
assert.equal(api.history(r).entries.length,12);assert.equal(api.history(r).entries[0].sprite,'original');
console.log('ok bounded revision count retains first original');
const large={sprite:'x'.repeat(7000000),info:{}};
for(let i=0;i<5;i++)api.commit(large,{sprite:String(i).repeat(7000000),info:{}},'Large');
assert(api.history(large).entries.reduce((n,e)=>n+e.sprite.length,0)<=24000000);
console.log('ok revision byte budget');
r.sprite='external';assert.equal(api.history(r).entries.length,1);assert.equal(api.history(r).entries[0].sprite,'external');
console.log('ok external edits reset stale history');
console.log('ALL PASSED');
