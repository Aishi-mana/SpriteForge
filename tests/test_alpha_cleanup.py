from _common import *
from engine import alpha_cleanup, styles, pixelize, main
from PIL import ImageDraw

im=Image.new("RGBA",(128,128),(0,255,0,255))
d=ImageDraw.Draw(im)
d.rectangle((12,12,115,115),fill=(40,50,80,255))
d.rectangle((25,25,48,50),fill=(0,255,0,255))
d.rectangle((70,25,95,50),fill=(255,255,255,255))
d.point((60,60),fill=(0,255,0,255))
out,info=alpha_cleanup.clean(im,30,"smart",(0,255,0),soft=False)
ok(out.getpixel((0,0))[3]==0,"exterior removed")
ok(out.getpixel((30,30))[3]==0,"enclosed pocket removed")
ok(out.getpixel((80,30))==(255,255,255,255),"white armor preserved with green key")
ok(out.getpixel((60,60))[3]==255,"tiny matching detail preserved")
out,_=alpha_cleanup.clean(im,30,"manual",(0,255,0),[(30,30)],False)
ok(out.getpixel((30,30))[3]==0 and out.getpixel((0,0))[3]==255,"manual pocket only")
out,_=alpha_cleanup.clean(im,30,"all",(0,255,0),soft=False)
ok(out.getpixel((60,60))[3]==0,"aggressive mode removes tiny matches")
out,_=alpha_cleanup.clean(im,30,"edge",(0,255,0),soft=False)
ok(out.getpixel((30,30))[3]==255,"edge mode retains enclosed region")
repaired,_=alpha_cleanup.clean(out,30,"manual",(0,255,0),[(30,30)],False)
ok(repaired.getpixel((0,0))[3]==0 and repaired.getpixel((30,30))[3]==0,"existing alpha preserved")
ok(pixelize.remove_bg(im,30).getpixel((30,30))[3]==0,"pixel integration")
hd,_=styles.finish(im,256,True,30,(0,255,0))
ok(hd.getpixel((60,60))[3]==0 and hd.getpixel((160,60))[3]==255,"HD integration")
res=main.alpha_cleanup_ep(main.AlphaCleanupParams(image=main.b64(im),background="green",mode="smart"))
ok(res["info"]["pockets"]==1,"API reports pocket count")
# Magic mode preserves exact retained RGBA, including interior clear holes.
magic=Image.new("RGBA",(32,32),(235,235,235,255))
md=ImageDraw.Draw(magic)
md.rectangle((0,16,31,31),fill=(210,210,210,255))
md.rectangle((8,5,23,26),fill=(30,40,50,255))
md.rectangle((12,10,19,17),fill=(235,235,235,255))
md.point((15,13),fill=(0,0,0,0))
out,info=alpha_cleanup.clean(magic,30,"magic",None,soft=True)
ok(out.getpixel((0,0))[3]==0 and out.getpixel((0,31))[3]==0,"magic removes exterior shades")
ok(out.getpixel((12,10))==magic.getpixel((12,10)) and out.getpixel((8,5))==magic.getpixel((8,5)),"magic retains exact interior and hard edges")
ok(magic.getpixel((0,0))[3]==255,"magic does not mutate source")
blank=Image.new("RGBA",(8,8),(255,255,255,255))
out,info=alpha_cleanup.clean(blank,30,"magic",(255,255,255))
ok(out.tobytes()==blank.tobytes() and info["removed"]==0,"magic guards fully empty result")
res=main.alpha_cleanup_ep(main.AlphaCleanupParams(image=main.b64(magic),background="auto",mode="magic",tolerance=30))
ok(res["info"]["removed"]>0,"magic API mode")
done("test_alpha_cleanup")
